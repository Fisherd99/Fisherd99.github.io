import fs from 'node:fs'
import { createHash } from 'node:crypto'
import { INSTRUMENTS } from '../.vitepress/theme/score-player/alphatab.mjs'

const hashes = Object.fromEntries([...new Set(INSTRUMENTS.map(item => item.soundFont))].sort().map(url => [
  url, createHash('sha256').update(fs.readFileSync(new URL(`../public${url}`, import.meta.url))).digest('hex')
]))
const output = new URL('../.vitepress/generated/soundfont-hashes.mjs', import.meta.url)
const content = `// Generated by scripts/generate-soundfont-hashes.mjs; do not edit.\nexport default ${JSON.stringify(hashes, null, 2)}\n`
if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) fs.writeFileSync(output, content)
console.log(`Verified ${Object.keys(hashes).length} soundfont files; SHA-256 manifest generated.`)
